test('Telegram saved language overrides device defaults and a new selection syncs to the bot',async({page})=>{
 let saved='ru';const writes=[];
 await page.addInitScript(()=>{window.Telegram={WebApp:{initData:'signed-session-fixture',initDataUnsafe:{user:{language_code:'en'}},ready(){},expand(){}}};});
 await page.route('**/api/preferences/language',async route=>{const data=route.request().postDataJSON();expect(route.request().headers()['x-telegram-init-data']).toBe('signed-session-fixture');if(data.action==='set'){saved=data.language;writes.push(saved);}await route.fulfill({json:{ok:true,language:saved}});});
 await page.goto('/?tab=profile');
 await expect(page.locator('.topbar select')).toHaveValue('ru');
 await page.locator('.topbar select').selectOption('en');
 await expect.poll(()=>writes).toEqual(['en']);
 await page.reload();await expect(page.locator('.topbar select')).toHaveValue('en');
 await expect(page.getByRole('heading',{name:'App settings',exact:true})).toBeVisible();
});
